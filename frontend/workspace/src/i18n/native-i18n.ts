export function nativeText(locale: string, source: string | undefined): string {
  if (!source) return source ?? ""
  return locale === "zh" || locale === "zht" ? (CHINESE[source] ?? source) : source
}

export function useNativeI18n() {
  let language: ReturnType<typeof useLanguage>
  try {
    language = useLanguage()
  } catch {
    // A few isolated component tests mount a pane without the application
    // providers. Preserve source copy there; production always has Language.
    return (source: string | undefined) => source ?? ""
  }
  return (source: string | undefined) => {
    if (!source) return source ?? ""
    const key = EXISTING[source]
    return key ? language.t(key) : nativeText(language.locale(), source)
  }
}
